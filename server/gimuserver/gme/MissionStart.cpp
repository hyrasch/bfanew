#include "App.hpp"
#include "Handlers.hpp"
#include "StubPlayer.hpp"

#include <chrono>
#include <filesystem>
#include <fstream>
#include <sstream>

/*
* MissionStart ("jE6Sp0q4"): "Begin Quest" (MissionStartScene::initConnect).
*
* The reply carries everything the battle needs, because the battle tables are not among the
* downloaded MSTs: the battles of the mission (BattleGroupMst), the enemies on the field with
* their positions and drops (BattleMonsterGroupMst / ...PartsMst), their stats (MonsterMst),
* their AI (AIMst) and enemy-only skills (MonsterSkillMst), plus the run's serial id
* (MissionNum, MissionInfo::setMissionSerialID) and the MissionStartInfo echo.
*
* The battle data is read from deploy/battle/<mission_id>.json, one MissionBattleData per
* mission, generated by tools/build_battles.py from the 2014 datamine captures.
*
* STUB: no persistence, so the energy shown afterwards is the initial one minus this mission,
* the serial id is the start time and nothing is remembered for MissionEnd.
*/

HANDLEF(MissionStart)
{
	MissionStartReq req = {};
	const auto& ec = glz::read<glz::opts{.error_on_unknown_keys = false}>(req, json);
	if (ec)
	{
		const auto& fmte = glz::format_error(ec, json);
		LOG_DEBUG << "Gme MissionStart Error during JSON read: " << fmte;
		co_return HandleResult::error("Deserialization error", fmte);
	}

	const auto missionId = req.mission.mission_id;
	LOG_DEBUG << "MissionStart: mission " << missionId << " deck " << req.mission.deck_num
		<< " helper " << req.mission.reinforce_user_id;

	const auto path = std::filesystem::path("battle") / (std::to_string(missionId) + ".json");
	std::ifstream in(path, std::ios::binary);
	if (!in)
	{
		LOG_WARN << "MissionStart: no battle data at " << path.string();
		co_return HandleResult::error("No battle data", "mission " + std::to_string(missionId));
	}
	std::stringstream ss;
	ss << in.rdbuf();
	const std::string text = ss.str();

	MissionBattleData data = {};
	const auto& ec1 = glz::read<glz::opts{.error_on_unknown_keys = false}>(data, text);
	if (ec1)
	{
		const auto& fmte = glz::format_error(ec1, text);
		LOG_ERROR << "MissionStart: bad battle data " << path.string() << ": " << fmte;
		co_return HandleResult::error("Bad battle data", fmte);
	}

	const auto& scfg = theServer()->cache().serverConfig();
	const auto now = std::chrono::system_clock::now();
	const auto nowUnix = std::chrono::duration_cast<std::chrono::seconds>(now.time_since_epoch()).count();

	MissionStartResp resp = {};

	resp.start_info.reinforce_user_id = req.mission.reinforce_user_id;
	resp.start_info.friend_point = scfg.initialFriendPoints;
	resp.start_info.mission_id = missionId;
	resp.start_info.reinforce_info = "";
	resp.start_info.deck_num = req.mission.deck_num;

	resp.mission_num.serial_id = std::to_string(nowUnix);
	theServer()->rememberRun(resp.mission_num.serial_id, missionId);
	resp.mission_num.bonus_type = 0;
	resp.mission_num.bonus_rate = "0";
	resp.mission_num.drop_info = "";

	StubPlayer::FillTeam(resp.team_info, scfg);
	resp.team_info.action_point = std::max<int32_t>(0, resp.team_info.action_point - data.energy_use);

	resp.battle_groups = std::move(data.battle_groups);
	resp.monster_groups = std::move(data.monster_groups);
	resp.parts = std::move(data.parts);
	resp.monsters = std::move(data.monsters);
	resp.ai = std::move(data.ai);
	resp.skills = std::move(data.skills);

	std::string buffer{};
	const auto& ec2 = glz::write_json(resp, buffer);
	if (ec2)
	{
		const auto& glze = glz::format_error(ec2, buffer);
		LOG_DEBUG << "Gme MissionStart Error during JSON writing: " << glze;
		co_return HandleResult::error("Serialization error", glze);
	}

	co_return HandleResult::success(buffer);
}
